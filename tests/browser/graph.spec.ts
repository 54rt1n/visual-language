  await page.getByRole('button', { name: 'Create topic', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Topics' })).toHaveCount(0)
  await expect(page.locator('.svelte-flow__node-root')).toHaveCount(1)
  await expect(page.locator('.svelte-flow__node-root')).toContainText('Travel practice')
  await page.getByRole('button', { name: 'Topics', exact: true }).click()
  const topic = page.getByRole('article', { name: 'Travel practice', exact: true })
  await topic.getByRole('button', { name: 'Rename', exact: true }).click()
  await page.getByLabel('Topic name', { exact: true }).fill('Travel Mandarin')
  await page.getByRole('button', { name: 'Save name', exact: true }).click()
  await page.getByRole('article', { name: 'Travel Mandarin', exact: true }).getByRole('button', { name: 'Open topic', exact: true }).click()
  await openTools(page)
  await page.getByRole('button', { name: 'Bookmark node', exact: true }).click()
  await close(page)
  await page.getByRole('button', { name: 'Topics', exact: true }).click()
  await page.getByRole('article', { name: 'Conversation', exact: true }).getByRole('button', { name: 'Open topic', exact: true }).click()
