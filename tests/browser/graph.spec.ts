import { openTool } from './navigation'
import { expect, test, type Page } from '@playwright/test'

async function ready(page: Page) { await page.goto('/'); await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible() }
async function openTools(page: Page) { await openTool(page, 'Node tools'); await expect(page.getByRole('dialog', { name: 'Node tools' })).toBeVisible() }
async function close(page: Page) { await page.getByRole('button', { name: 'Close dialog' }).click() }
async function savedOverride(page: Page) { await page.getByRole('button', { name: 'Save branch override' }).click(); await expect(page.getByRole('status').filter({ hasText: 'Branch override saved.' })).toBeVisible() }
async function configure(page: Page) {
  await openTool(page, 'AI connection')
  await page.getByRole('combobox', { name: 'Provider', exact: true }).selectOption('custom')
  await page.getByLabel('API endpoint').fill('https://api.graph-fixture.example/v1')
  await page.getByLabel('Model ID', { exact: true }).fill('global-fixture')
  await page.getByLabel('Custom endpoint API key').fill('graph-fixture-secret')
  await page.getByRole('button', { name: 'Save connection', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'AI connection' })).toHaveCount(0)
}
async function backup(page: Page) {
  await openTool(page, 'Backup & restore')
  const pending = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download full backup' }).click()
  const file = await pending, stream = await file.createReadStream(), chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  await close(page)
  return JSON.parse(Buffer.concat(chunks).toString())
}

