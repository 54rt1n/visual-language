test('original export helper does not create missing databases or modify records and omits credentials', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
  const script = readFileSync(new URL('../../scripts/export-original-in-browser.js', import.meta.url), 'utf8')
  await page.evaluate(script)
  expect(await page.evaluate(async () => (await indexedDB.databases()).some(db => db.name === 'VLLADatabase'))).toBe(false)
  const fixture = originalFixture()
  fixture.nodes.find(node => node.id === 'mandarin')!.data.wordSegments = [{ text: '谢谢', startIndex: 0, endIndex: 2, pinyin: 'xiè xie', apiKey: 'OMIT-SEGMENT-KEY' }]
  await page.evaluate(async fixture => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => {
      const request = indexedDB.open('VLLADatabase', 1)
      request.onupgradeneeded = () => { for (const table of ['nodes', 'edges', 'vocabulary', 'goals']) request.result.createObjectStore(table, { keyPath: 'id' }) }
      request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error)
    })
    const tx = db.transaction(['nodes', 'edges', 'vocabulary', 'goals'], 'readwrite')
    const done = new Promise<void>((resolve, reject) => { tx.oncomplete = () => resolve(); tx.onabort = () => reject(tx.error) })
    for (const table of ['nodes', 'edges', 'vocabulary'] as const) for (const row of fixture[table]) tx.objectStore(table).add(row)
    tx.objectStore('goals').add({ id: 'goal', text: 'Not part of the content adapter' })
    await done; db.close()
  }, fixture)
  const download = page.waitForEvent('download')
  await page.evaluate(script)
  const stream = await (await download).createReadStream(), chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  const content = Buffer.concat(chunks).toString(), data = JSON.parse(content)
  expect(data.nodes).toHaveLength(fixture.nodes.length)
  expect(data.nodes.find((node: { id: string }) => node.id === 'mandarin').data.wordSegments).toEqual([{ text: '谢谢', startIndex: 0, endIndex: 2, pinyin: 'xiè xie' }])
  const byId = (a: Record<string, unknown>, b: Record<string, unknown>) => String(a.id).localeCompare(String(b.id))
  expect(data.vocabulary.toSorted(byId)).toEqual(fixture.vocabulary.toSorted(byId))
  expect(content).not.toMatch(/OMIT-ORIGINAL-KEY|OMIT-RAW-ERROR-KEY|OMIT-SEGMENT-KEY|never-contact|Not part of the content adapter/)
  expect(await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>(resolve => { const request = indexedDB.open('VLLADatabase'); request.onsuccess = () => resolve(request.result) })
    try { return await new Promise<boolean>(resolve => { const request = db.transaction('nodes').objectStore('nodes').get('model'); request.onsuccess = () => resolve(request.result.data.apiKey === 'OMIT-ORIGINAL-KEY') }) }
    finally { db.close() }
  })).toBe(true)
  await openTool(page, 'Backup & restore')
  await page.getByText('Import from the original project', { exact: true }).click()
  await page.getByLabel('Choose original project file').setInputFiles({ name: 'helper-export.json', mimeType: 'application/json', buffer: Buffer.from(content) })
  await expect(page.getByText('Original-project content conversion', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Replace workspace', exact: true })).toBeDisabled()
})

