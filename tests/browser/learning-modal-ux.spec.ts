import { openTool } from './navigation'
import { expect, test, type Locator, type Page } from '@playwright/test'
import type { Workspace } from '../../src/lib/domain/workspace'

async function backup(page: Page): Promise<Workspace> {
  await openTool(page, 'Backup & restore')
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download full backup', exact: true }).click()
  const stream = await (await pending).createReadStream(), chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  return JSON.parse(Buffer.concat(chunks).toString()).data
}

async function usable(button: Locator) {
  await expect(button).toBeInViewport({ ratio: 1 })
  expect(await button.evaluate(element => {
    const rect = element.getBoundingClientRect()
    return element.contains(document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2))
  })).toBe(true)
}

for (const width of [390, 320]) test(`saving a word and starting a lesson stay manageable on a ${width}px short screen`, async ({ page }) => {
  await page.setViewportSize({ width, height: 568 })
  const external: string[] = [], errors: string[] = []
  page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:4173')) external.push(r.url()) })
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Save for practice', exact: true }).click()
  const dialog = page.getByRole('dialog'), save = dialog.getByRole('button', { name: 'Save for practice', exact: true })
  await expect(dialog.getByRole('textbox')).toHaveCount(2)
  await expect(dialog.locator('.practice-options')).not.toHaveAttribute('open', '')
  await usable(save)
  await save.click()
  await expect(page.getByLabel('Mandarin word or phrase')).toBeFocused() // Native required-field validation still works from the footer.
  await page.getByLabel('Mandarin word or phrase').fill('学习')
  await page.getByLabel('Meaning in this context').fill('to study; to learn')
  await dialog.locator('.modal-body').evaluate(element => { element.scrollTop = 0 })
  await page.screenshot({ path: `test-results/capture-simple-short-${width}.png`, fullPage: true })
  const originalFooter = await save.boundingBox()
  await dialog.getByText(/^Practice options/).click()
  await page.getByRole('checkbox', { name: 'Type the Mandarin answer' }).uncheck()
  await page.getByRole('checkbox', { name: 'Choose an answer (multiple choice)', exact: true }).check()
  await page.getByLabel('Sense / distinction').fill('learning a skill')
  await dialog.locator('.modal-body').evaluate(element => { element.scrollTop = element.scrollHeight })
  await usable(save)
  expect((await save.boundingBox())!.y).toBeCloseTo(originalFooter!.y, 0)
  await save.click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const saved = await backup(page)
  expect(saved.items).toHaveLength(1)
  expect(saved.items[0]).toMatchObject({ canonicalText: '学习', meaning: 'to study; to learn', senseKey: 'learning a skill' })
  expect(saved.cards).toHaveLength(1)
  expect(saved.cards[0]).toMatchObject({ skill: 'recognition', status: 'new', introducedAt: null, dueAt: null })
  expect(saved.events).toHaveLength(0)

  await page.getByRole('button', { name: 'Daily review', exact: true }).click()
  const start = page.getByRole('dialog').getByRole('button', { name: 'Start practice', exact: true })
  await usable(start)
  await expect(dialog.locator('.lesson-options')).not.toHaveAttribute('open', '')
  await page.getByRole('combobox', { name: /^Your Mandarin level/ }).selectOption('intermediate')
  await page.getByLabel('Learning goal', { exact: true }).fill('Understand words in everyday conversations.')
  await dialog.locator('.modal-body').evaluate(element => { element.scrollTop = 0 })
  await expect(page.getByLabel('Learning goal', { exact: true })).toBeInViewport({ ratio: 1 })
  await expect(page.getByRole('combobox', { name: /^Your Mandarin level/ })).toBeInViewport({ ratio: 1 })
  await expect(page.getByLabel('Explanation language', { exact: true })).toBeInViewport({ ratio: 1 })
  await page.screenshot({ path: `test-results/teacher-simple-short-${width}.png`, fullPage: true })
  await page.getByText(/^Lesson options/).click()
  await page.getByLabel('Distinct due cards per lesson').fill('3')
  await page.getByLabel('New items after due queue is exhausted').fill('2')
  await usable(start)
  await start.click()
  await expect(page.getByRole('button', { name: 'Teach this item', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Pause & close', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const paused = await backup(page)
  expect(paused.learners[0]).toMatchObject({ level: 'intermediate', maxReviewCards: 3, maxNewItems: 2 })
  expect(paused.sessions[0]).toMatchObject({ status: 'paused', maxReviewCards: 3, maxNewItems: 2 })
  expect(paused.cards).toEqual(saved.cards)
  expect(paused.events).toEqual(saved.events)
  expect(external).toEqual([]); expect(errors).toEqual([])
})

test('a short-screen quiz keeps its question, submission and explicit help confirmation reachable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 568 })
  const external: string[] = []
  page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:4173')) external.push(r.url()) })
  await page.goto('/#demo')
  await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
  const before = await backup(page)
  await page.getByRole('button', { name: 'Daily review', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Start practice', exact: true }).click()
  await page.getByRole('button', { name: 'Review next due card', exact: true }).click()
  await expect(page.locator('.question .prompt')).toBeFocused()
  await expect(page.locator('.question .prompt')).toBeInViewport({ ratio: 1 })
  for (const option of await page.locator('.question .option').all()) {
    const size = await option.evaluate(element => ({ height: element.getBoundingClientRect().height, fontSize: Number.parseFloat(getComputedStyle(element).fontSize) }))
    expect(size.height).toBeGreaterThanOrEqual(48); expect(size.fontSize).toBeGreaterThanOrEqual(16)
  }
  await usable(page.getByRole('button', { name: 'Submit answer', exact: true }))
  await page.screenshot({ path: 'test-results/quiz-question-short.png', fullPage: true })
  await page.getByRole('button', { name: 'Hint', exact: true }).click()
  await usable(page.getByRole('button', { name: 'Confirm help', exact: true }))
  await expect(page.locator('.modal-footer')).toContainText('Help records this review as not recalled')
  await page.screenshot({ path: 'test-results/quiz-help-short.png', fullPage: true })
  await page.getByRole('button', { name: 'Keep trying independently', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Expected answer', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Reveal answer', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm help', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Expected answer', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pause & close', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const after = await backup(page)
  const added = after.events.filter(event => !before.events.some(old => old.id === event.id))
  expect(added.filter(event => event.kind === 'review')).toHaveLength(1)
  expect(added.find(event => event.kind === 'review')).toMatchObject({ aid: 'reveal', outcome: 'notRecalled' })
  expect(after.attempts).toEqual(before.attempts)
  expect(external).toEqual([])
})
