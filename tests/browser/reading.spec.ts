const reply = '我想喝咖啡，谢谢。银行行长喜欢音乐。'
const explanation = { meaning: 'coffee', explanation: '咖啡 is the drink after 喝 (to drink).', sentenceMeaning: 'I would like to drink coffee, thank you.', uncertain: false,
  pronunciation: { pinyin: 'kā fēi', note: 'Both syllables have a level first tone.' } }
async function setup(page: Page, source = reply, explainSelection?: (selected: string) => typeof explanation) {
  const requests: Record<string, unknown>[] = []
  await page.route('https://reading-fixture.example/v1/chat/completions', async route => {
    const request = route.request().postDataJSON(); requests.push(request)
    const readingMessage = request.messages.find((m: { role: string; content: string }) => m.role === 'user' && m.content.includes('selectedText'))
    const selected = readingMessage ? JSON.parse(readingMessage.content).selectedText : ''
    const material = explainSelection ? explainSelection(selected) : selected === '喝咖啡' ? { ...explanation, meaning: 'to drink coffee', explanation: '喝 means to drink; 咖啡 is its object, coffee.', pronunciation: { pinyin: 'hē kā fēi', note: 'All three syllables have a level first tone.' } } : explanation
    const frame = { model: 'reading-fixture', choices: [{ index: 0, delta: { content: readingMessage ? JSON.stringify(material) : source }, finish_reason: null }] }
    await route.fulfill({ status: 200, contentType: 'text/event-stream', body: `data: ${JSON.stringify(frame)}\n\ndata: {"choices":[{"index":0,"delta":{},"finish_reason":"stop"}]}\n\ndata: [DONE]\n\n` })
  })
  await page.goto('/'); await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
  await openTool(page, 'AI connection')
  await page.getByRole('combobox', { name: 'Provider', exact: true }).selectOption('custom')
  await page.getByLabel('API endpoint').fill('https://reading-fixture.example/v1')
  await page.getByLabel('Model ID', { exact: true }).fill('reading-fixture')
  await page.getByLabel('Custom endpoint API key').fill('synthetic-reading-key')
  await page.getByRole('button', { name: 'Save connection' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Message to Zheng' }).fill('Explain a useful sentence.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.word-text .word').first()).toBeVisible()
  await page.locator('.assistant .configuration > summary').click()
  await page.locator('.assistant').getByRole('button', { name: 'Hide pinyin', exact: true }).click()
  return requests
}
async function backup(page: Page) {
  await openTool(page, 'Backup & restore')
  const pending = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download full backup' }).click()
  const file = await pending, stream = await file.createReadStream(), buffers: Buffer[] = []
  for await (const chunk of stream!) buffers.push(Buffer.from(chunk))
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  return JSON.parse(Buffer.concat(buffers).toString())
}

function longReply() {
  const lead = Array.from({ length: 160 }, (_, index) => `第${index + 1}段：今天我们学习中文。\n`).join('').slice(0, 1598) + '\n'
  return lead + '图书馆。𠮷野。银行行长喜欢音乐。' + '银行'.repeat(80) + '。最后我们喝咖啡。'
}

