test('a delayed dictionary follows the selected word in the reading modal', async ({ browser }) => {
  const context = await browser.newContext({ storageState: returningVisitor, serviceWorkers: 'block' }), page = await context.newPage()
  let release!: () => void, started = false
  const pending = new Promise<void>(resolve => { release = resolve })
  try {
    await context.route('**/dictionaries/*.txt.gz', async route => { started = true; await pending; await route.continue() })
    const requests = await setup(page)
    await page.getByRole('button', { name: 'Read response', exact: true }).click()
    const reader = page.getByRole('region', { name: 'Response reader' })
    await reader.getByRole('button', { name: 'Play 银行', exact: true }).click()
    await expect.poll(() => started).toBe(true)
    await reader.getByRole('button', { name: 'Play 咖啡', exact: true }).click()
    release()
    await expect(reader.getByRole('region', { name: 'Selected word definition' })).toContainText('(loanword) coffee')
    await expect(reader.getByRole('region', { name: 'Selected word definition' })).not.toContainText('bank')
    expect(requests).toHaveLength(1)
  } finally { release(); await context.close() }
})

