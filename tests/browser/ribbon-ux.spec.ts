import { expect, test } from '@playwright/test'

for (const [width, height] of [[1440, 900], [390, 568], [320, 568], [568, 320]] as const) test(`grouped navigation and exploration remain usable at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height })
  await page.goto('/')
  await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
  const rail = page.getByRole('navigation', { name: 'Workspace tools' })
  await rail.getByRole('button', { name: 'Show tool labels' }).click()
  await expect(rail.getByRole('group', { name: 'Learning' })).toContainText('Save for practice')
  await expect(rail.getByRole('group', { name: 'Workspace' })).toContainText('Topics')
  await expect(rail.getByRole('button', { name: 'Backup & restore' })).toHaveCount(0)
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(rail.getByRole('button', { name: 'Explore a topic', exact: true })).toBeFocused()
  await expect(page.getByRole('tooltip')).toContainText('Create a lesson')
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Explore a topic', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('.search-options')).not.toHaveAttribute('open', '')
  await page.getByLabel('Topic or scenario', { exact: true }).fill('Ordering breakfast')
  const create = dialog.getByRole('button', { name: 'Create lesson', exact: true })
  await expect(create).toBeEnabled()
  await page.screenshot({ path: `test-results/explore-${width}.png`, fullPage: true })
  await expect(create).toBeInViewport({ ratio: 1 })
  await dialog.locator('.search-options > summary').click()
  await expect(page.getByRole('combobox', { name: 'Save in topic', exact: true })).toBeVisible()
  await expect(create).toBeInViewport({ ratio: 1 })
  expect(await create.evaluate(element => { const r = element.getBoundingClientRect(); return element.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) })).toBe(true)
  await page.keyboard.press('Escape')
  await expect(rail.getByRole('button', { name: 'Explore a topic', exact: true })).toBeFocused()
  await rail.getByRole('button', { name: 'Explore a topic', exact: true }).click()
  await expect(page.getByLabel('Topic or scenario', { exact: true })).toHaveValue('Ordering breakfast')
  await page.keyboard.press('Escape')
  await rail.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Audio & pinyin settings', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Audio & pinyin settings', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(rail.getByRole('button', { name: 'Settings', exact: true })).toBeFocused()
  await rail.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Show Zheng’s portrait' }).uncheck()
  await expect(page.getByRole('checkbox', { name: 'Show Zheng’s portrait' })).toBeEnabled()
  await page.keyboard.press('Escape')
  await rail.getByRole('button', { name: 'More tools', exact: true }).click()
  await page.getByRole('button', { name: 'Backup & restore', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Backup & restore', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(rail.getByRole('button', { name: 'More tools', exact: true })).toBeFocused()
  await page.screenshot({ path: `test-results/ribbon-${width}.png`, fullPage: true })
})
