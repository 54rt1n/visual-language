test('normal and demo tabs do not conflict, while two demo tabs retain stale-write protection', async ({ page, context }) => {
  await ready(page)
  await page.getByRole('textbox', { name: 'Message to Zheng' }).fill('Normal tab remains separate.')
  await data(page); const normal = await download(page); await close(page)
  const demo = await context.newPage(); await ready(demo, true)
  const secondDemo = await context.newPage(); await ready(secondDemo, true)
  await advance(demo, 1)
  await expect(secondDemo.getByRole('alert')).toContainText('Another tab changed')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await data(page); expect((await download(page)).backup.data).toEqual(normal.backup.data)
})
