import { openTool } from './navigation'
import { expect, test, type Page } from '@playwright/test'

async function ready(page: Page) {
  await page.goto('/')
  await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
}
async function backup(page: Page) {
  await openTool(page, 'Backup & restore')
  await expect(page.getByRole('dialog', { name: 'Backup & restore' })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download full backup' }).click()
  const download = await downloadPromise
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  return Buffer.concat(chunks)
}

test('production canvas saves multiple topics and restores a full backup in a clean profile', async ({ page, browser }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await ready(page)
  await page.getByRole('button', { name: 'New topic' }).click()
  await page.getByRole('textbox', { name: 'Message to Zheng' }).fill('Practice ordering tea tomorrow.')
  const buffer = await backup(page), exported = JSON.parse(buffer.toString('utf8'))
  expect(exported.data.nodes.filter((n: { type: string }) => n.type === 'root')).toHaveLength(2)
  expect(exported.data.view.composerDraft).toBe('Practice ordering tea tomorrow.')
  expect(buffer.toString('utf8')).not.toMatch(/apiKey|Authorization|keyOrigin/)
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await expect(page.getByRole('button', { name: 'More tools', exact: true })).toBeFocused()
  await page.screenshot({ path: 'test-results/workspace-canvas.png', fullPage: true })

  const fresh = await browser.newContext()
  const restored = await fresh.newPage()
  const externalRequests: string[] = []
  restored.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:4173')) externalRequests.push(new URL(request.url()).origin) })
  await ready(restored)
  await openTool(restored, 'Backup & restore')
  await restored.getByLabel('Choose backup file').setInputFiles({ name: 'workspace.json', mimeType: 'application/json', buffer })
  await expect(restored.getByRole('button', { name: 'Replace workspace', exact: true })).toBeDisabled()
  await restored.getByRole('checkbox', { name: 'Replace the current workspace' }).check()
  await restored.getByRole('button', { name: 'Replace workspace', exact: true }).click()
  await expect(restored.getByText('Workspace restored.', { exact: false })).toBeVisible()
  await restored.getByRole('button', { name: 'Close dialog' }).click()
  await expect(restored.getByRole('textbox', { name: 'Message to Zheng' })).toHaveValue('Practice ordering tea tomorrow.')
  await restored.reload()
  await expect(restored.getByText('Saved on this device', { exact: false })).toBeVisible()
  await expect(restored.getByRole('textbox', { name: 'Message to Zheng' })).toHaveValue('Practice ordering tea tomorrow.')
  expect(await restored.evaluate(() => localStorage.getItem('vl-settings-v2'))).toBeNull()
  expect(externalRequests).toEqual([])
  expect(errors).toEqual([])
  await fresh.close()
})

test('invalid import and cancelled preview retain the current workspace', async ({ page }) => {
  await ready(page)
  const buffer = await backup(page)
  await page.getByLabel('Choose backup file').setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{') })
  await expect(page.getByRole('alert')).toContainText('not valid JSON')
  await page.getByLabel('Choose backup file').setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer })
  await page.getByRole('button', { name: 'Cancel import' }).click()
  await expect(page.getByRole('button', { name: 'Replace workspace', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Restore recovery checkpoint' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await expect(page.locator('.svelte-flow__node-root')).toHaveCount(1)
})

test('a second tab detects changes and cannot silently overwrite them', async ({ page, context }) => {
  await ready(page)
  const second = await context.newPage()
  await ready(second)
  await page.getByRole('button', { name: 'New topic' }).click()
  await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
  await expect(second.getByRole('alert')).toContainText('Another tab changed')
  await expect(second.getByRole('button', { name: 'New topic' })).toBeDisabled()
  second.on('dialog', dialog => dialog.accept())
  await second.getByRole('button', { name: 'Reload saved state' }).click()
  await expect(second.locator('.svelte-flow__node-root')).toHaveCount(1)
  const saved = JSON.parse((await backup(second)).toString('utf8'))
  expect(saved.data.nodes.filter((node: { type: string }) => node.type === 'root')).toHaveLength(2)
})

test('fixture streaming reply persists content and actual model without a real provider request', async ({ page }) => {
  await ready(page)
  await openTool(page, 'AI connection')
  await page.getByRole('combobox', { name: 'Provider', exact: true }).selectOption('custom')
  await page.getByLabel('API endpoint').fill('https://api.fixture.example/v1')
  await page.getByLabel('Model ID').fill('requested-fixture')
  await page.getByLabel('Custom endpoint API key').fill('fixture-key-not-a-real-credential')
  await page.getByRole('button', { name: 'Save connection', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'AI connection' })).toHaveCount(0)
  await page.route('https://api.fixture.example/v1/chat/completions', route => route.fulfill({ status: 200, contentType: 'text/event-stream',
    body: 'data: {"model":"actual-fixture","choices":[{"index":0,"delta":{"content":"你好！很高兴认识你。"},"finish_reason":null}]}\n\ndata: {"choices":[{"index":0,"delta":{},"finish_reason":"stop"}]}\n\ndata: [DONE]\n\n' }))
  await page.getByRole('textbox', { name: 'Message to Zheng' }).fill('Teach me a greeting.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.svelte-flow__node-assistant')).toContainText('你好！很高兴认识你。')
  const buffer = await backup(page), exported = JSON.parse(buffer.toString('utf8'))
  expect(exported.data.nodes.find((n: { type: string }) => n.type === 'assistant').data).toMatchObject({ state: 'complete', model: 'actual-fixture', provider: 'custom' })
  expect(buffer.toString('utf8')).not.toContain('fixture-key-not-a-real-credential')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.reload()
  await expect(page.locator('.svelte-flow__node-assistant')).toContainText('你好！很高兴认识你。')
})

test('explicit Alibaba compatibility persists and sends non-thinking requests without exporting key authority', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await ready(page)
  await openTool(page, 'AI connection')
  await page.getByRole('combobox', { name: 'Provider', exact: true }).selectOption('custom')
  await page.getByLabel('API endpoint').fill('https://api.alibaba-fixture.example/v1')
  await page.getByLabel('Model ID').fill('qwen-fixture')
  await page.getByLabel('API compatibility').selectOption('alibaba')
  await expect(page.getByText('Token Plan subscriptions', { exact: false })).toBeVisible()
  await page.getByLabel('Custom endpoint API key').fill('alibaba-fixture-not-a-real-credential')
  await page.getByRole('button', { name: 'Save connection', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'AI connection' })).toHaveCount(0)
  await page.reload()
  await openTool(page, 'AI connection')
  await expect(page.getByLabel('API compatibility')).toHaveValue('alibaba')
  expect(await page.getByRole('dialog').evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: 'test-results/alibaba-settings-mobile.png', fullPage: true })
  const requests: Record<string, unknown>[] = []
  await page.route('https://api.alibaba-fixture.example/v1/chat/completions', async route => {
    requests.push(route.request().postDataJSON())
    await route.fulfill({ status: 200, contentType: 'text/event-stream', body: 'data: {"model":"qwen-fixture","choices":[{"delta":{"content":"OK"},"finish_reason":"stop"}]}\n\ndata: [DONE]\n\n' })
  })
  await page.getByRole('button', { name: 'Test connection' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Connected to Custom endpoint' })).toBeVisible()
  expect(requests).toHaveLength(1)
  expect(requests[0]).toMatchObject({ model: 'qwen-fixture', enable_thinking: false, stream: true })
  await page.getByRole('button', { name: 'Close dialog' }).click()
  const buffer = await backup(page), exported = JSON.parse(buffer.toString('utf8'))
  expect(exported.data.preferences.profiles.custom).toEqual({ baseUrl: 'https://api.alibaba-fixture.example/v1', model: 'qwen-fixture', compatibility: 'alibaba' })
  expect(buffer.toString('utf8')).not.toMatch(/apiKey|keyOrigin|alibaba-fixture-not-a-real-credential/)
})

test('settings reports partial persistence instead of silently closing on a workspace conflict', async ({ page, context }) => {
  await ready(page)
  const other = await context.newPage()
  await ready(other)
  await other.getByRole('button', { name: 'New topic' }).click()
  await expect(page.getByRole('alert')).toContainText('Another tab changed')
  await openTool(page, 'AI connection')
  await page.getByRole('combobox', { name: 'Provider', exact: true }).selectOption('custom')
  await page.getByLabel('API endpoint').fill('https://api.fixture.example/v1')
  await page.getByLabel('Model ID').fill('conflict-fixture')
  await page.getByLabel('Custom endpoint API key').fill('fixture-not-a-real-credential')
  await page.getByRole('button', { name: 'Save connection', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('status')).toContainText('Keys were saved in this browser, but workspace backup preferences could not be saved')
  await expect(page.getByRole('button', { name: 'Save connection', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('vl-settings-v2')!).profiles.custom.model)).toBe('conflict-fixture')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  const buffer = await backup(other), exported = JSON.parse(buffer.toString('utf8'))
  expect(exported.data.preferences.profiles.custom.model).toBe('')
  expect(exported.data.nodes.filter((node: { type: string }) => node.type === 'root')).toHaveLength(2)
})
