import { expect, test, type Page } from '@playwright/test'
import { openTool } from './navigation'

async function close(page: Page) { await page.getByRole('button', { name: 'Close dialog', exact: true }).click() }
async function lessons(page: Page) {
  await expect(page.getByRole('button', { name: 'Lessons', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Lessons', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Lessons', exact: true })
  await expect(dialog).toBeVisible()
  return dialog
}
async function answer(page: Page, wrong = false) {
  const dialog = page.getByRole('dialog', { name: 'Your lesson', exact: true })
  await dialog.getByRole('radio', { name: wrong ? 'I am sorry' : 'thank you', exact: true }).check()
  await dialog.getByRole('button', { name: 'Check answer', exact: true }).click()
}
async function finishQuiz(page: Page, wrong = false) {
  const dialog = page.getByRole('dialog', { name: 'Your lesson', exact: true })
  await expect(dialog).toContainText('Quiz · Question 1 of 1')
  await expect(dialog.getByRole('button', { name: 'Check answer', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: 'Show answer', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: 'Skip this step', exact: true })).toHaveCount(0)
  await dialog.getByRole('radio', { name: wrong ? 'I am sorry' : 'thank you', exact: true }).check()
  await expect(dialog.getByText('Correct.', { exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Submit quiz', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: 'Lesson complete', exact: true })).toBeVisible()
}
async function finishLearning(page: Page, wrong = false) {
  const dialog = page.getByRole('dialog', { name: 'Your lesson', exact: true })
  await dialog.getByRole('button', { name: 'Try it', exact: true }).click()
  await answer(page)
  await dialog.getByRole('button', { name: 'Start quiz', exact: true }).click()
  await finishQuiz(page, wrong)
}

test('lesson retries, saved practice, review, history and archive work together on a short mobile screen', async ({ page }) => {
  test.setTimeout(60_000)
  await page.setViewportSize({ width: 390, height: 568 })
  const errors: string[] = [], external: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:4173')) external.push(request.url()) })
  await page.goto('/#demo')
  await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Fit View', exact: true }).click()
  await page.locator('.svelte-flow__node[data-id="demo-everyday-reply"]').click({ position: { x: 15, y: 15 } })
  await page.getByRole('button', { name: 'Practice this conversation', exact: true }).click()
  const lesson = page.getByRole('dialog', { name: 'Your lesson', exact: true })
  const phrases = lesson.getByRole('group', { name: 'Phrases to practice', exact: true }).getByRole('checkbox')
  await expect(phrases).toHaveCount(2)
  for (const phrase of await phrases.all()) await phrase.uncheck()
  await phrases.first().check()
  await lesson.getByRole('button', { name: 'Prepare lesson', exact: true }).click()
  await finishLearning(page, true)
  await expect(lesson).toContainText('0/10 points')
  await lesson.getByRole('button', { name: 'Try quiz again', exact: true }).click()
  await finishQuiz(page)
  await expect(lesson).toContainText('Passed · +1 point')
  await lesson.getByRole('button', { name: 'Back to lessons', exact: true }).click()
  let collection = page.getByRole('dialog', { name: 'Lessons', exact: true })
  const savedLesson = collection.getByRole('article', { name: 'DEMO · Everyday Mandarin', exact: true })
  await expect(collection).toContainText('Level 1 of 4 · 1/10 points')
  await expect(collection).toContainText('Next: Level 2 at 3 points.')
  await expect(collection.getByRole('region', { name: 'Learning streak', exact: true })).toContainText('1 day in a row')
  await savedLesson.getByRole('button', { name: 'Practice', exact: true }).click()
  await lesson.getByRole('button', { name: 'Try it', exact: true }).click()
  await lesson.getByRole('radio', { name: 'thank you', exact: true }).check()
  await lesson.getByRole('button', { name: 'Pause & back to lessons', exact: true }).click()
  collection = page.getByRole('dialog', { name: 'Lessons', exact: true })
  await expect(savedLesson.getByRole('button', { name: 'Continue', exact: true })).toBeVisible()
  await savedLesson.getByRole('button', { name: 'Archive', exact: true }).click()
  await expect(collection.getByRole('article')).toHaveCount(1)
  await expect(collection.getByRole('article', { name: 'Order a cup of tea', exact: true })).toBeVisible()
  await collection.getByRole('checkbox', { name: /Show archived/ }).check()
  await expect(collection).toContainText('Level 1 of 4 · 1/10 points')
  await savedLesson.getByRole('button', { name: 'Restore lesson', exact: true }).click()
  await collection.getByRole('checkbox', { name: /Show archived/ }).uncheck()
  await savedLesson.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(lesson.getByRole('radio', { name: 'thank you', exact: true })).toBeChecked()
  await lesson.getByRole('button', { name: 'Pause & back to lessons', exact: true }).click()
  await expect(collection).toBeVisible()
  await close(page)
  await openTool(page, 'Demo workspace')
  await page.getByText('Demo options', { exact: true }).click()
  await page.getByLabel('Days to advance').fill('1')
  await page.getByRole('button', { name: 'Advance demo clock', exact: true }).click()
  await expect(page.getByText('Advanced the demo', { exact: false })).toBeVisible()
  await close(page)
  collection = await lessons(page)
  await expect(collection).toContainText('Ready for review')
  await expect(savedLesson.getByRole('button', { name: 'Review', exact: true })).toHaveClass(/ready/)
  await expect(collection.getByRole('button', { name: 'Create a lesson', exact: true })).not.toHaveClass(/ready/)
  await expect(savedLesson.getByRole('button', { name: 'Resume saved practice', exact: true })).toBeVisible()
  expect(await collection.evaluate(element => element.querySelector('.modal-body')!.scrollWidth <= element.querySelector('.modal-body')!.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: 'test-results/lessons-mobile-due.png', fullPage: true })
  await savedLesson.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(lesson).toContainText('Quiz · Question 1 of 1')
  await finishQuiz(page)
  await expect(lesson).toContainText('2/10 points')
  await lesson.getByRole('button', { name: 'Back to lessons', exact: true }).click()
  await savedLesson.getByText('Progress and history (3 completed)', { exact: true }).click()
  await expect(collection).toContainText('Not yet passed')
  await expect(collection).toContainText('1/1 correct without help')
  await expect(collection).toContainText('Next: Level 2 at 3 points.')
  await expect(collection.getByRole('button', { name: 'Create a lesson', exact: true })).toHaveClass(/ready/)
  await savedLesson.locator('details').evaluate(element => element.scrollIntoView({ block: 'start' }))
  await expect(savedLesson.getByRole('listitem').first()).toBeInViewport()
  await page.screenshot({ path: 'test-results/lessons-mobile-history.png', fullPage: true })
  expect(errors).toEqual([]); expect(external).toEqual([])
})
