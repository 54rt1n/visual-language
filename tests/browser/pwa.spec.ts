import { openTool } from './navigation'
import { expect, test } from '@playwright/test'

for (const dismiss of ['Close dialog', 'Escape']) {
  test(`update panel can ${dismiss} while a local save is delayed`, async ({ page }) => {
    await page.goto('/')
    await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
    await page.evaluate(() => {
      const original = crypto.subtle.digest.bind(crypto.subtle), pending: (() => void)[] = []
      crypto.subtle.digest = (...args) => new Promise((resolve, reject) => {
        pending.push(() => { void original(...args).then(resolve, reject) })
      })
      Object.assign(window, { releaseDelayedWrites: () => { crypto.subtle.digest = original; for (const release of pending) release() } })
    })
    const draft = 'Keep this draft while saving is delayed.'
    await page.getByRole('textbox', { name: 'Message to Zheng' }).fill(draft)
    await openTool(page, 'App updates')
    await page.getByRole('button', { name: 'Save & prepare to update', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Saving…', exact: true })).toBeDisabled()
    if (dismiss === 'Escape') await page.keyboard.press('Escape')
    else await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('textbox', { name: 'Message to Zheng' })).toHaveValue(draft)
    await page.evaluate(() => (window as Window & { releaseDelayedWrites: () => void }).releaseDelayedWrites())
    await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('textbox', { name: 'Message to Zheng' })).toHaveValue(draft)
  })
}

test('an update check that never returns times out and permits retry or dismissal', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    ServiceWorkerRegistration.prototype.update = () => new Promise(() => {})
  })
  await page.clock.install()
  await openTool(page, 'App updates')
  await page.getByRole('button', { name: 'Check for app update', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Checking for updates…', exact: true })).toBeDisabled()
  await page.clock.fastForward(15_001)
  await expect(page.getByRole('status').filter({ hasText: 'Could not check for an update' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Check for app update', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Check for app update', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Checking for updates…', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('production manifest, icons, scoped shell cache and loaded-app offline backup', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Saved on this device', { exact: false })).toBeVisible()
  const manifestLink = await page.locator('link[rel="manifest"]').getAttribute('href')
  expect(manifestLink).toBe('./manifest.webmanifest')
  const manifest = await (await page.request.get('/manifest.webmanifest')).json()
  expect(manifest).toMatchObject({ id: './', start_url: './', scope: './', display: 'standalone' })
  for (const icon of manifest.icons) {
    const size = Number(icon.sizes.split('x')[0])
    const dimensions = await page.evaluate(async src => { const image = new Image(); image.src = src; await image.decode(); return [image.naturalWidth, image.naturalHeight] }, `/${icon.src}`)
    expect(dimensions).toEqual([size, size])
  }
  const registration = await page.evaluate(async () => { const r = await navigator.serviceWorker.ready; return { scope: r.scope, active: r.active?.state } })
  expect(registration).toEqual({ scope: 'http://127.0.0.1:4173/', active: 'activated' })
  await page.reload()
  expect(await page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  const cached = await page.evaluate(async () => { const names = (await caches.keys()).filter(k => k.startsWith('visual-language-shell:')); return Promise.all(names.map(async key => ({ key, urls: (await (await caches.open(key)).keys()).map(r => r.url) }))) })
  expect(cached).toHaveLength(1)
  expect(cached[0]!.urls.some(url => url.endsWith('/index.html'))).toBe(true)
  expect(cached[0]!.urls.every(url => url.startsWith('http://127.0.0.1:4173/'))).toBe(true)
  expect(cached[0]!.urls.some(url => /tavily|completions|settings/.test(url))).toBe(false)
  expect(cached[0]!.urls.some(url => url.includes('/avatars/'))).toBe(false)
  expect(cached[0]!.urls.some(url => url.includes('/reading-model/'))).toBe(false)
  const budget = await (await page.request.get('/asset-budget.json')).json()
  expect(budget.shell.core.bytes).toBeLessThanOrEqual(1.5 * 1024 * 1024)
  expect(budget.shell.language.bytes).toBeGreaterThan(0)
  expect(budget.shell.language.bytes).toBeLessThanOrEqual(3 * 1024 * 1024)
  expect(budget.shell.meanings.bytes).toBeGreaterThan(0)
  expect(budget.shell.meanings.bytes).toBeLessThanOrEqual(4.25 * 1024 * 1024)
  expect(budget.shell.bytes).toBe(budget.shell.core.bytes + budget.shell.language.bytes + budget.shell.meanings.bytes)
  expect(budget.pronunciation.bytes).toBe(81_154_648)
  expect(budget.pronunciation.bytes).toBeLessThanOrEqual(budget.pronunciation.limit)
  expect(cached[0]!.urls.map(url => new URL(url).pathname).sort()).toEqual(budget.shell.files.map((entry: { file: string }) => '/' + entry.file).sort())
  await openTool(page, 'App updates')
  await expect(page.getByText('App shell cache ready.', { exact: false })).toBeVisible()
  await expect(page.getByText('Add to Home Screen', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await context.setOffline(true)
  await page.getByRole('textbox', { name: 'Message to Zheng' }).fill('Offline draft retained until I reconnect.')
  await openTool(page, 'App updates')
  await page.getByRole('button', { name: 'Save & prepare to update' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Drafts are saved' })).toBeVisible()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await openTool(page, 'Backup & restore')
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download full backup' }).click()
  const file = await pending, stream = await file.createReadStream(), chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  expect(JSON.parse(Buffer.concat(chunks).toString()).data.view.composerDraft).toBe('Offline draft retained until I reconnect.')
  await context.setOffline(false)
})
